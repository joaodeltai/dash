export const clone = v => JSON.parse(JSON.stringify(v));

/* Turns flatten() output back into the `rows` shape hydrate() consumes, adding the columns flatten does not emit. */
export function flatToRows(flat, extra = {}) {
  const arr = t => [...flat[t].values()].map(r => ({ ...r }));
  const ws = [...flat.workspaces.values()][0];
  const profile = [...flat.profiles.values()][0];
  const state = [...flat.member_state.values()][0];
  return {
    workspace: ws,
    profile,
    members: arr('members').map(m => ({ ...m, user_id: m.user_id ?? null, last_seen_at: null })),
    teams: arr('teams'),
    projects: arr('projects'),
    project_members: arr('project_members'),
    tasks: arr('tasks'),
    subtasks: arr('subtasks'),
    task_dependencies: arr('task_dependencies'),
    files: arr('files'),
    comments: arr('comments'),
    activity: arr('activity'),
    notifications: [],
    events: arr('events'),
    saved_views: arr('saved_views'),
    task_favorites: arr('task_favorites'),
    project_favorites: arr('project_favorites'),
    member_state: state,
    ...extra,
  };
}
